/**
 * Generate src/generated/* from the repo's committed JSON Schemas (schemas/, exported from pydantic).
 *
 *   npm run gen:types -w @geoui/react-adapter
 *
 * Two files, both committed and drift-checked by src/__tests__/schemas.test.ts:
 * - generated/geo-intent.ts   TypeScript types for GeoIntent, LayerRef, Viewport, TimeWindow and each extension's fields
 * - generated/schemas.ts      the schema documents themselves as `as const` literals (so describe() returns them verbatim)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile, type JSONSchema } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
export const SCHEMAS_DIR = resolve(here, "../../../schemas");
export const GENERATED_DIR = resolve(here, "../src/generated");

const BANNER = "/* Generated by scripts/gen-types.ts from schemas/ (exported from pydantic). Do not edit. */\n";
/** Each extension's published document, `schemas/<dir>/schema.json`; the dir is the tail of its URI. */
const EXTENSIONS = [
  { dir: "ext/compare/v1.0.0", typeName: "CompareFields", constName: "COMPARE_SPEC" },
  { dir: "ext/chart/v1.0.0", typeName: "ChartFields", constName: "CHART_SPEC" },
  { dir: "ext/raster-styling/v1.0.0", typeName: "RasterStylingFields", constName: "RASTER_STYLING_SPEC" },
] as const;

function readJson(name: string): Record<string, unknown> {
  return JSON.parse(readFileSync(join(SCHEMAS_DIR, name), "utf8")) as Record<string, unknown>;
}

/** Keys of a published schema.json that are not part of the fields' JSON Schema. */
const DOCUMENT_ONLY_KEYS = ["$schema", "$id", "x-geoui"];

/**
 * A published `schema.json` as the `ExtensionSpec.describe()` shape the SDK advertises (the inverse of
 * Python's `ExtensionSpec.schema_document()`): `uri` is the `$id`, the metadata comes from `x-geoui`,
 * and `fields_schema` is the document without those keys. Keys are sorted, like Python's export.
 */
export function specFromSchemaDocument(doc: Record<string, unknown>): Record<string, unknown> {
  const meta = doc["x-geoui"] as Record<string, unknown>;
  const fields_schema = Object.fromEntries(Object.entries(doc).filter(([key]) => !DOCUMENT_ONLY_KEYS.includes(key)));
  return {
    fields_schema,
    keys: meta.keys,
    name: meta.name,
    required: meta.required,
    scope: meta.scope,
    summary: meta.summary,
    uri: doc.$id,
  };
}

function readSpec(ext: (typeof EXTENSIONS)[number]): Record<string, unknown> {
  return specFromSchemaDocument(readJson(join(ext.dir, "schema.json")));
}

/** pydantic titles every property ("Id", "Bbox"); without this each would become its own type alias. */
function stripPropertyTitles(schema: unknown): unknown {
  if (Array.isArray(schema)) return schema.map(stripPropertyTitles);
  if (schema && typeof schema === "object") {
    const out: Record<string, unknown> = {};
    for (const [key, value] of Object.entries(schema as Record<string, unknown>)) {
      if (key === "properties" && value && typeof value === "object") {
        out[key] = Object.fromEntries(
          Object.entries(value as Record<string, unknown>).map(([name, prop]) => {
            const rest = { ...((prop ?? {}) as Record<string, unknown>) };
            delete rest.title;
            return [name, stripPropertyTitles(rest)];
          }),
        );
      } else {
        out[key] = stripPropertyTitles(value);
      }
    }
    return out;
  }
  return schema;
}

const compileOptions = { bannerComment: "", additionalProperties: false, style: { printWidth: 120 } } as const;

export async function generate(): Promise<Record<string, string>> {
  const core = readJson("geo_intent.json");
  let types = BANNER + (await compile(stripPropertyTitles(core) as JSONSchema, "GeoIntent", compileOptions));
  for (const ext of EXTENSIONS) {
    const spec = readSpec(ext);
    // LayerRef / TimeWindow referenced from $defs are already declared by the core compile above.
    types += "\n" + (await compile(stripPropertyTitles(spec.fields_schema) as JSONSchema, ext.typeName, { ...compileOptions, declareExternallyReferenced: false }));
  }

  let schemas = BANNER;
  schemas += `export const GEO_INTENT_SCHEMA = ${JSON.stringify(core, null, 2)} as const;\n`;
  for (const ext of EXTENSIONS) {
    schemas += `\nexport const ${ext.constName} = ${JSON.stringify(readSpec(ext), null, 2)} as const;\n`;
  }
  return { "geo-intent.ts": types, "schemas.ts": schemas };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const files = await generate();
  for (const [name, text] of Object.entries(files)) {
    writeFileSync(join(GENERATED_DIR, name), text);
    console.log(`wrote src/generated/${name}`);
  }
}
